async function main() {
  console.log("Syncing portfolio -> template...");
  console.log(`  from: ${repoRoot}`);
  console.log(`  to:   ${templateDir}`);

  await emptyDir(templateDir);
  await copyTree(repoRoot, templateDir);
  await copy(starterContentDir, templateDir, { overwrite: true });
  await writeFile(
    path.join(templateDir, "public/hero-placeholder.svg"),
    HERO_PLACEHOLDER_SVG
  );
  await writeFile(
    path.join(templateDir, "TEMPLATE.md"),
    `# Portfolio template\n\nAuto-generated by \`pnpm template:sync\`. Do not edit manually — changes will be overwritten.\n`
  );

  await ensureAppFavicon(templateDir);

  console.log("Template sync complete.");
}

async function ensureAppFavicon(rootDir) {
  const appFavicon = path.join(rootDir, "src/app/favicon.ico");
  const publicFavicon = path.join(rootDir, "public/favicon.ico");

  try {
    const stat = await fs.stat(appFavicon);
    if (stat.size > 0) return;
  } catch {
    // missing — copy below
  }

  await copy(publicFavicon, appFavicon);
}

async function copyTree(sourceDir, targetDir) {
  const entries = await fs.readdir(sourceDir, { withFileTypes: true });

  for (const entry of entries) {
    if (EXCLUDED_DIRS.has(entry.name)) continue;
    if (EXCLUDED_FILES.has(entry.name)) continue;

    const sourcePath = path.join(sourceDir, entry.name);
    const targetPath = path.join(targetDir, entry.name);

    if (entry.isDirectory()) {
      await ensureDir(targetPath);
      await copyTree(sourcePath, targetPath);
      continue;
    }

    const ext = path.extname(entry.name);
    if (TEXT_EXTENSIONS.has(ext)) {
      let content = await fs.readFile(sourcePath, "utf8");
      content = applyReplacements(content, entry.name);
      await writeFile(targetPath, content);
    } else {
      await copy(sourcePath, targetPath);
    }
  }
}

function applyReplacements(content, fileName) {
  for (const [from, to] of REPLACEMENTS) {
    content = content.split(from).join(to);
  }

  if (fileName === "ui-theme.css") {
    for (const [from, to] of THEME_REPLACEMENTS) {
      content = content.split(from).join(to);
    }
    for (const [from, to] of PAGE_GRADIENT_REPLACEMENTS) {
      content = content.split(from).join(to);
    }
  }

  if (fileName === "package.json") {
    content = content.replace(/"prepare": "husky",?\n?/g, "");
  }

  return content;
}

